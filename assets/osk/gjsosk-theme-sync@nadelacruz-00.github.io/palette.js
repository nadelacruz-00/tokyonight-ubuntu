// Pure helpers (no Shell imports) so they can be tested with `gjs -m tests/gjs/theme-sync.test.js`.

const HEX = '#[0-9a-fA-F]{6}';

// Read the colours Rewaita writes into ~/.config/gtk-4.0/gtk.css.
// Returns null when the file lacks the basic window/card colours.
export function parsePalette(css) {
    const v = name => css.match(new RegExp(`--${name}:\\s*(${HEX})\\s*;`))?.[1] ?? null;
    const d = name => css.match(new RegExp(`@define-color\\s+${name}\\s+(${HEX})\\s*;`))?.[1] ?? null;
    const p = {
        bg: v('window-bg-color'),
        fg: v('window-fg-color'),
        card: v('card-bg-color'),
        accentBg: d('accent_bg_color') ?? v('accent-bg-color'),
        accentFg: d('accent_fg_color') ?? v('accent-fg-color'),
    };
    if (!p.bg || !p.fg || !p.card)
        return null;
    p.accentBg ??= p.fg;
    p.accentFg ??= p.bg;
    return p;
}

export function rgb(hex) {
    const n = parseInt(hex.slice(1), 16);
    return [(n >> 16) & 255, (n >> 8) & 255, n & 255];
}

// Same perceived-brightness test GJS OSK uses to pick `regular` (dark) keys.
export function isDark(hex) {
    const [r, g, b] = rgb(hex);
    return Math.sqrt(0.299 * r * r + 0.587 * g * g + 0.114 * b * b) <= 127.5;
}

// Key colours for the dark (`regular`) keyboard.  `.boxLay .key` outranks
// every GJS OSK colour rule, so load order does not matter.
export function buildCss(p) {
    const [ar, ag, ab] = rgb(p.accentBg);
    return `/* generated by gjsosk-theme-sync from the Rewaita palette */
.boxLay .key.regular {
    background-color: ${p.card};
    color: ${p.fg};
}
.boxLay .key.regular:pressed {
    background-color: rgba(${ar}, ${ag}, ${ab}, 0.35);
    color: ${p.fg};
}
.boxLay .key.selected.regular,
.boxLay .key.selected.regular:pressed {
    background-color: ${p.accentBg};
    color: ${p.accentFg};
}
`;
}
